#!/usr/bin/env bash
# Build, sign and install the local-only iPhone app.
#
# The local-only app pairs with the owner's Macs through `hmux://` codes
# over Tailscale and has no hmux account, Iroh relay, presence, push, billing
# or telemetry (see ios/Config/LocalOnly.xcconfig). Because there is no account,
# the authenticated dogfood flow in ios/scripts/reload.sh does not apply; this
# script is the install path for that app only.
#
# The app is built from a throwaway copy of the project with the Cloud VPN and
# notification-service extensions removed, so it signs as one bundle with a
# development profile covering the bundle id (by default the team's wildcard
# profile already on this Mac).
#
# Usage: ios/scripts/build-local-only.sh [--device-id <id>] [--no-install]
#                                        [--profile <uuid>] [--team <id>]
#                                        [--bundle-id <id>]
#                                        [--ota-dir <dir> --ota-url <https-url>]
#
# --ota-dir/--ota-url publish an over-the-air install instead of a cable
# install: the signed .ipa, an itms-services manifest and an install page are
# written to <dir>, which a web server must serve at <https-url> (iOS requires
# HTTPS). Open <https-url>/install.html on the iPhone to install.
#
# Team, bundle ID, app name, profile, OTA folder and URL come from .env-local in the
# repository root (see .env-local.template), so none of them live in the
# repo. The options above override the file for one run.
set -euo pipefail

IOS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO_DIR="$(cd "$IOS_DIR/.." && pwd)"
# shellcheck source=../../scripts/lib/local-only-env.sh
source "$REPO_DIR/scripts/lib/local-only-env.sh"
hmux_local_only_load_env "$REPO_DIR"
TEAM_ID="$HMUX_LOCAL_TEAM_ID"
BUNDLE_ID="$HMUX_LOCAL_IOS_BUNDLE_ID"
PROFILE_UUID="${HMUX_LOCAL_IOS_PROFILE:-}"
APP_NAME="${HMUX_LOCAL_IOS_APP_NAME:-hmux}"
DEVICE_ID="${HMUX_IPHONE_DEVICE_ID:-}"
INSTALL=1
OTA_DIR="${HMUX_LOCAL_IOS_OTA_DIR:-}"
OTA_URL="${HMUX_LOCAL_IOS_OTA_URL:-}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --device-id) DEVICE_ID="$2"; shift 2 ;;
    --no-install) INSTALL=0; shift ;;
    --profile) PROFILE_UUID="$2"; shift 2 ;;
    --team) TEAM_ID="$2"; shift 2 ;;
    --bundle-id) BUNDLE_ID="$2"; shift 2 ;;
    --ota-dir) OTA_DIR="$2"; shift 2 ;;
    --ota-url) OTA_URL="$2"; shift 2 ;;
    -h|--help) sed -n '2,26p' "$0"; exit 0 ;;
    *) echo "error: unknown argument: $1" >&2; exit 2 ;;
  esac
done

if [[ -n "$OTA_DIR" || -n "$OTA_URL" ]]; then
  [[ -n "$OTA_DIR" && -n "$OTA_URL" ]] \
    || { echo "error: --ota-dir and --ota-url go together" >&2; exit 2; }
  [[ "$OTA_URL" == https://* ]] \
    || { echo "error: --ota-url must be https (iOS refuses other installs)" >&2; exit 2; }
  OTA_URL="${OTA_URL%/}"
fi

if [[ -z "$DEVICE_ID" && -f "$HOME/.config/hmux/iphone-device-id" ]]; then
  DEVICE_ID="$(tr -d '[:space:]' < "$HOME/.config/hmux/iphone-device-id")"
fi

# Pick a development profile that covers the bundle id: an exact App ID wins
# over the team wildcard.
find_profile() {
  local dir file plist appid best="" wildcard=""
  plist="$(mktemp)"
  for dir in "$HOME/Library/Developer/Xcode/UserData/Provisioning Profiles" \
             "$HOME/Library/MobileDevice/Provisioning Profiles"; do
    [[ -d "$dir" ]] || continue
    for file in "$dir"/*.mobileprovision; do
      [[ -f "$file" ]] || continue
      security cms -D -i "$file" > "$plist" 2>/dev/null || continue
      [[ "$(/usr/libexec/PlistBuddy -c 'Print :Entitlements:get-task-allow' "$plist" 2>/dev/null)" == "true" ]] || continue
      appid="$(/usr/libexec/PlistBuddy -c 'Print :Entitlements:application-identifier' "$plist" 2>/dev/null)"
      local uuid
      uuid="$(/usr/libexec/PlistBuddy -c 'Print :UUID' "$plist")"
      if [[ "$appid" == "$TEAM_ID.$BUNDLE_ID" ]]; then
        best="$uuid"
      elif [[ "$appid" == "$TEAM_ID.*" ]]; then
        wildcard="$uuid"
      fi
    done
  done
  rm -f "$plist"
  echo "${best:-$wildcard}"
}

if [[ -z "$PROFILE_UUID" ]]; then
  PROFILE_UUID="$(find_profile)"
fi
if [[ -z "$PROFILE_UUID" ]]; then
  echo "error: no development profile for $TEAM_ID.$BUNDLE_ID or $TEAM_ID.* on this Mac." >&2
  echo "       Create one in the Apple Developer portal (or open any team project in Xcode once), then rerun." >&2
  exit 1
fi
echo "==> Signing $BUNDLE_ID with team $TEAM_ID, profile $PROFILE_UUID"

cat > "$IOS_DIR/Config/LocalOnly.signing.xcconfig" <<EOF
// Generated by ios/scripts/build-local-only.sh. Do not commit.
HMUX_LOCAL_ONLY_BUNDLE_IDENTIFIER = $BUNDLE_ID
HMUX_LOCAL_ONLY_TEAM = $TEAM_ID
PRODUCT_DISPLAY_NAME = $APP_NAME
EOF

"$REPO_DIR/scripts/ensure-ghosttykit.sh"

# Throwaway project: no extensions, LocalOnly.xcconfig on the app's Release.
LOCAL_PROJECT="$IOS_DIR/hmux-ios-local-only.xcodeproj"
rm -rf "$LOCAL_PROJECT"
mkdir -p "$LOCAL_PROJECT"
cp -R "$IOS_DIR/hmux-ios.xcodeproj/project.xcworkspace" "$LOCAL_PROJECT/"
/usr/bin/python3 - "$IOS_DIR/hmux-ios.xcodeproj/project.pbxproj" "$LOCAL_PROJECT/project.pbxproj" <<'PY'
import re
import sys

source, target = sys.argv[1], sys.argv[2]
text = open(source).read()
# Drop both extensions from the app's embed phase and its dependencies.
embed_files = (
    "files = (D4E2A0010000000000000002 /* NotificationService.appex in Embed App Extensions */, "
    "C10DA0010000000000000002 /* CloudVPN.appex in Embed App Extensions */);"
)
if text.count(embed_files) != 1:
    sys.exit("error: app extension embed phase not found")
text = text.replace(embed_files, "files = ();")
for dependency in ["D4E2A00F0000000000000001", "C10DA0060000000000000002"]:
    text, count = re.subn(r"\n\t+" + dependency + r" /\* PBXTargetDependency \*/,", "", text)
    if count != 1:
        sys.exit(f"error: app target dependency {dependency} not found")
# The app's Release configuration builds from LocalOnly.xcconfig.
old = "path = Release.xcconfig;"
if text.count(old) != 1:
    sys.exit("error: Release.xcconfig reference not found")
text = text.replace(old, "path = LocalOnly.xcconfig;")
open(target, "w").write(text)
PY

# The local Swift packages are workspace members, so the throwaway project
# needs its own workspace and scheme pointing at it.
mkdir -p "$LOCAL_PROJECT/xcshareddata/xcschemes"
sed 's#container:hmux-ios.xcodeproj#container:hmux-ios-local-only.xcodeproj#g' \
  "$IOS_DIR/hmux-ios.xcodeproj/xcshareddata/xcschemes/hmux-ios.xcscheme" \
  > "$LOCAL_PROJECT/xcshareddata/xcschemes/hmux-ios-local-only.xcscheme"
LOCAL_WORKSPACE="$IOS_DIR/hmux-local-only.xcworkspace"
rm -rf "$LOCAL_WORKSPACE"
mkdir -p "$LOCAL_WORKSPACE"
sed 's#group:hmux-ios.xcodeproj#group:hmux-ios-local-only.xcodeproj#' \
  "$IOS_DIR/hmux.xcworkspace/contents.xcworkspacedata" \
  > "$LOCAL_WORKSPACE/contents.xcworkspacedata"
if [[ -d "$IOS_DIR/hmux.xcworkspace/xcshareddata" ]]; then
  cp -R "$IOS_DIR/hmux.xcworkspace/xcshareddata" "$LOCAL_WORKSPACE/"
fi

DERIVED_DATA="$HOME/Library/Developer/Xcode/DerivedData/hmux-ios-local-only"
APP_PATH="$DERIVED_DATA/Build/Products/Release-iphoneos/hmux.app"
xcodebuild \
  -workspace "$LOCAL_WORKSPACE" \
  -scheme hmux-ios-local-only \
  -configuration Release \
  -destination "generic/platform=iOS" \
  -derivedDataPath "$DERIVED_DATA" \
  HMUX_GIT_SHA="$(git -C "$REPO_DIR" rev-parse --short HEAD)" \
  CODE_SIGNING_ALLOWED=NO \
  build

[[ -d "$APP_PATH" ]] || { echo "error: built app not found" >&2; exit 1; }
if [[ -d "$APP_PATH/PlugIns" ]]; then
  echo "error: the local-only app must not embed extensions" >&2
  exit 1
fi
plist_value() { /usr/libexec/PlistBuddy -c "Print :$1" "$APP_PATH/Info.plist"; }
[[ "$(plist_value HMUXLocalOnly)" == "YES" ]] \
  || { echo "error: built app is not marked local-only" >&2; exit 1; }
[[ "$(plist_value CFBundleIdentifier)" == "$BUNDLE_ID" ]] \
  || { echo "error: built app has the wrong bundle id" >&2; exit 1; }
[[ "$(plist_value CFBundleDisplayName)" == "$APP_NAME" ]] \
  || { echo "error: built app has the wrong display name" >&2; exit 1; }
# Sign outside Xcode: the team wildcard profile is Xcode-managed, which
# Xcode refuses for manual signing, while codesign only needs the profile's
# certificate and App ID to cover this bundle.
PROFILE_FILE=""
for dir in "$HOME/Library/Developer/Xcode/UserData/Provisioning Profiles" \
           "$HOME/Library/MobileDevice/Provisioning Profiles"; do
  [[ -f "$dir/$PROFILE_UUID.mobileprovision" ]] && PROFILE_FILE="$dir/$PROFILE_UUID.mobileprovision"
done
[[ -n "$PROFILE_FILE" ]] || { echo "error: profile $PROFILE_UUID not found" >&2; exit 1; }
WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT
security cms -D -i "$PROFILE_FILE" > "$WORK_DIR/profile.plist"
# Sign with the profile's first certificate whose private key is in the
# keychain.
IDENTITY=""
index=0
while /usr/libexec/PlistBuddy -c "Print :DeveloperCertificates:$index" "$WORK_DIR/profile.plist" > "$WORK_DIR/cert.der" 2>/dev/null; do
  sha="$(openssl x509 -inform der -in "$WORK_DIR/cert.der" -noout -fingerprint -sha1 | sed 's/.*=//; s/://g')"
  if security find-identity -v -p codesigning | grep -q "$sha"; then
    IDENTITY="$sha"
    break
  fi
  index=$((index + 1))
done
[[ -n "$IDENTITY" ]] || { echo "error: no signing identity in this keychain matches profile $PROFILE_UUID" >&2; exit 1; }

cat > "$WORK_DIR/app.entitlements" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>application-identifier</key>
	<string>$TEAM_ID.$BUNDLE_ID</string>
	<key>com.apple.developer.team-identifier</key>
	<string>$TEAM_ID</string>
	<key>get-task-allow</key>
	<true/>
	<key>keychain-access-groups</key>
	<array>
		<string>$TEAM_ID.$BUNDLE_ID</string>
	</array>
</dict>
</plist>
PLIST
cp "$PROFILE_FILE" "$APP_PATH/embedded.mobileprovision"
if [[ -d "$APP_PATH/Frameworks" ]]; then
  find "$APP_PATH/Frameworks" -maxdepth 1 \( -name '*.framework' -o -name '*.dylib' \) -print0 \
    | while IFS= read -r -d '' nested; do
        codesign --force --sign "$IDENTITY" --timestamp=none "$nested"
      done
fi
codesign --force --sign "$IDENTITY" --timestamp=none \
  --entitlements "$WORK_DIR/app.entitlements" "$APP_PATH"
codesign --verify --strict "$APP_PATH"
echo "==> Built and signed $APP_NAME ($BUNDLE_ID)"

if [[ -n "$OTA_DIR" ]]; then
  version="$(plist_value CFBundleShortVersionString)"
  build="$(plist_value CFBundleVersion)"
  display_name="$(plist_value CFBundleDisplayName)"
  git_sha="$(git -C "$REPO_DIR" rev-parse --short HEAD)"
  built_at="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  mkdir -p "$OTA_DIR" "$WORK_DIR/ipa/Payload"
  cp -R "$APP_PATH" "$WORK_DIR/ipa/Payload/"
  (cd "$WORK_DIR/ipa" && /usr/bin/zip -qry "$WORK_DIR/hmux.ipa" Payload)
  mv "$WORK_DIR/hmux.ipa" "$OTA_DIR/hmux.ipa"
  cat > "$OTA_DIR/manifest.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>items</key>
	<array>
		<dict>
			<key>assets</key>
			<array>
				<dict>
					<key>kind</key>
					<string>software-package</string>
					<key>url</key>
					<string>$OTA_URL/hmux.ipa</string>
				</dict>
			</array>
			<key>metadata</key>
			<dict>
				<key>bundle-identifier</key>
				<string>$BUNDLE_ID</string>
				<key>bundle-version</key>
				<string>$version</string>
				<key>kind</key>
				<string>software</string>
				<key>title</key>
				<string>$display_name</string>
			</dict>
		</dict>
	</array>
</dict>
</plist>
PLIST
  cat > "$OTA_DIR/install.html" <<HTML
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>$display_name</title>
<style>
body { font-family: -apple-system, sans-serif; padding: 40px 20px; text-align: center; background: #1a1a1a; color: #fff; margin: 0; }
.card { background: #2a2a2a; border-radius: 16px; padding: 24px; margin: 16px auto; max-width: 420px; text-align: left; }
.card p { color: #aaa; font-size: 14px; line-height: 1.5; }
.btn { display: block; padding: 16px; background: #007AFF; color: #fff; text-decoration: none; border-radius: 12px; font-size: 17px; font-weight: 600; text-align: center; margin: 16px 0 8px; }
.info { font-family: 'SF Mono', monospace; font-size: 11px; color: #8f8; word-break: break-all; }
.kofi { display: inline-flex; align-items: center; gap: 8px; margin-top: 24px; padding: 10px 18px; background: #FF5E5B; color: #fff; text-decoration: none; border-radius: 999px; font-size: 15px; font-weight: 600; }
.kofi:active { opacity: 0.8; }
</style>
</head>
<body>
<h1>$display_name</h1>
<div class="card">
<p>Private build, based on hmux, that connects only to your Macs over Tailscale. No account, relay or telemetry.</p>
<a class="btn" href="itms-services://?action=download-manifest&amp;url=$OTA_URL/manifest.plist">Install $display_name</a>
<p class="info">Bundle: $BUNDLE_ID<br>Version: $version ($build)<br>Git: $git_sha<br>Built: $built_at<br>Signed: team $TEAM_ID, development profile $PROFILE_UUID</p>
</div>
<a class="kofi" href="https://ko-fi.com/devicemanager">☕ Buy me a coffee</a>
</body>
</html>
HTML
  echo "==> Published OTA install: $OTA_URL/install.html"
  exit 0
fi

if [[ "$INSTALL" -eq 0 ]]; then
  exit 0
fi
if [[ -z "$DEVICE_ID" ]]; then
  echo "==> No iPhone selected. Connect it and rerun with --device-id <id> (see: xcrun devicectl list devices)."
  exit 0
fi
xcrun devicectl device install app --device "$DEVICE_ID" "$APP_PATH"
echo "==> Installed on $DEVICE_ID"
